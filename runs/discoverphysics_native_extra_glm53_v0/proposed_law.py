def discovered_law(pos1, pos2, p1, p2, velocity2, duration, **params):
    """
    Particle 2 moves in a central inverse-square field generated by the fixed source.
    The acceleration magnitude scales with p1 and inversely with p2.
    The trajectory is obtained by integrating the resulting two-dimensional Newtonian ODE.
    """
    import numpy as np
    from scipy.integrate import solve_ivp

    alpha = params.get("alpha", 1.0)

    def rhs(t, state):
        x, y, vx, vy = state
        r2 = x * x + y * y
        r32 = r2 * np.sqrt(r2)
        factor = -alpha * p1 / (p2 * r32)
        return [vx, vy, factor * x, factor * y]

    initial_state = [pos2[0], pos2[1], velocity2[0], velocity2[1]]
    solution = solve_ivp(
        rhs,
        (0.0, duration),
        initial_state,
        method="RK45",
        rtol=1e-6,
        atol=1e-8
    )
    final_state = solution.y[:, -1]
    return final_state[:2].tolist(), final_state[2:].tolist()


def fit_parameters():
    return {
        "alpha": {"init": 1.0, "bounds": [0.01, 10.0]}
    }
