"""Counterfactual native-gate replay using unchanged published programs.

The newer program was published as accepted under a DIFFERENT online history.
We do not claim it was rejected by the author, or generated by an attacker.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import sys
import time

import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / "vendor/BabaInWonderland"
sys.path.insert(0, str(UPSTREAM))
from scripts.data_collect.evaluate_offline_dataset import _load_state_archive_inputs
from scripts.data_collect.data_coverage import archive_state_input_to_canonical_text
from src.agents.manual_transition_explorer import ManualTransitionExplorer
from src.data import Transition
from src.discovery.program_pipeline import ProgramDiscoveryPipeline
from src.program_model.evaluator import ProgramEvaluator


def save(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n")


def sha(text):
    return hashlib.sha256(text.encode()).hexdigest()


class NoModelCalls:
    def generate_text(self, prompt):
        raise AssertionError("This diagnostic must not call a model")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=False)
    start = time.monotonic()
    history = ROOT / "runs/baba_program_history_full_v0"
    manifest = yaml.safe_load((UPSTREAM / "configs/custom_map_splits_dot_test.yaml").read_text())["original"]
    aliases = yaml.safe_load((UPSTREAM / "configs/experiment_config_online.yaml").read_text())["serialization"]["word_aliases"]
    results = []
    for variant in ["default", "wonderland"]:
        output = args.output / variant
        output.mkdir()
        with np.load(history / f"{variant}_correctness.npz", allow_pickle=False) as archive:
            matrix, versions = archive["correct"], archive["versions"]
        eligible = [i for i in range(1, len(versions))
                    if matrix[i-1].mean() >= .9
                    and (~matrix[i-1] & matrix[i]).any()
                    and (matrix[i-1] & ~matrix[i]).any()]
        if not eligible:
            results.append({"variant": variant, "status": "no_eligible_pair"})
            continue
        chosen = eligible[0]
        target_index = int(np.flatnonzero(~matrix[chosen-1] & matrix[chosen])[0])
        transitions, metadata = [], []
        for world_index, map_name in enumerate(manifest["all_train"], start=1):
            raws = _load_state_archive_inputs(UPSTREAM / "test_dataset/solution" / f"{map_name}_states.npz")
            states = [archive_state_input_to_canonical_text(s, word_aliases=aliases if variant == "wonderland" else None) for s in raws]
            rows = (UPSTREAM / "test_dataset/solution" / f"{map_name}_transitions.jsonl").read_text().splitlines()
            for row in map(json.loads, filter(None, rows)):
                transitions.append(Transition(state=states[row["state_index"]], action=row["action"],
                    next_state=states[row["next_state_index"]], reward=row.get("reward",0),
                    done=bool(row.get("done",False)), world_index=world_index, map_name=map_name))
                metadata.append({"map": map_name, "transition_index":row["transition_index"], "action":row["action"]})
        assert metadata == json.loads((history / f"{variant}_transitions.json").read_text())
        target = transitions[target_index]
        manual = output / "manual"
        manual.mkdir()
        save(manual / "target.json", {"previous_state_raw": target.state, "next_state_raw": target.next_state,
             "action": target.action, "env_index": target.world_index, "scenario_type": target.map_name})
        program_dir = ROOT / "vendor/BabaInWonderland_demo/programs" / variant
        before = (program_dir / f"{versions[chosen-1]}.py").read_text()
        after = (program_dir / f"{versions[chosen]}.py").read_text()
        evaluator = ProgramEvaluator(program_eval_workers=8)
        pipeline = ProgramDiscoveryPipeline(explorer=ManualTransitionExplorer(manual),
            llm_predictor=NoModelCalls(), evaluator=evaluator, output_dir=str(output / "native"),
            regression_group_sample_k=3, regression_witnesses_per_group=1,
            save_new_transition_images=False, random_seed=0, patch_format="function")
        pipeline.current_version = pipeline.repository.save_version(before, pipeline.current_version.version_id,
            {"reason": "Published program initialization for counterfactual gate replay, not a new learned update."})
        pipeline.current_source = before
        evaluated = evaluator.evaluate_source(before, transitions)
        assert [r.is_correct for r in evaluated.records] == matrix[chosen-1].tolist()
        protected = [t for t,c in zip(transitions, matrix[chosen-1]) if c]
        pipeline.canonical_d.merge(protected + [target])
        for transition in protected:
            pipeline._add_to_protected(transition, commit_version_override=pipeline.current_version.version_id)
        pipeline._sync_explorer_program_context(emit_log=False)
        before_context = pipeline._build_group_context_payload()
        save(output / "context_before.json", before_context)
        classes_before = pipeline._current_active_class_count()
        diag = pipeline._diagnose_candidate(source=after, patch_digest=sha(after), candidate_index=0,
                                            target=target, current_accuracy=1.0)
        save(output / "native_diagnosis.json", diag)
        assert diag["qualified_regression_reject"] and not diag["accepted_by_gate"]
        assert diag["protected_regressions"] == int((matrix[chosen-1] & ~matrix[chosen]).sum())
        feedback = pipeline._prepare_regression_feedback(target=target, diag=diag,
                                                         patch_digest=sha(after), candidate_source=after)
        save(output / "native_feedback.json", feedback)
        save(output / "context_after.json", pipeline._build_group_context_payload())
        result = {"variant": variant, "before": str(versions[chosen-1]), "candidate": str(versions[chosen]),
                  "baseline_sha256":sha(before), "candidate_sha256":sha(after),
                  "target":metadata[target_index], "protected_count":len(pipeline.protected_set),
                  "native_target_solved":diag["target_solved"], "native_protected_regressions":diag["protected_regressions"],
                  "native_qualified_rejection":diag["qualified_regression_reject"],
                  "class_count_before":classes_before, "class_count_after":pipeline._current_active_class_count(),
                  "split_events":len(feedback["split_events"]),
                  "witness_count":len(feedback["regression_witness_cases"]),
                  "accepted_program_unchanged":pipeline.current_source == before,
                  "new_model_calls":0, "new_environment_interactions":0,
                  "status":"completed"}
        results.append(result)
        evaluator.close()
        print(json.dumps(result),flush=True)
    save(args.output / "summary.json", {
        "status":"completed", "results":results, "wall_time_s":time.monotonic()-start,
        "selection":"Development selection: first chronological adjacent pair per variant with baseline accuracy >=0.9 and both gains and losses; first newly correct target in manifest order.",
        "initial_state":"One new root class containing baseline-correct training solution transitions; no reconstruction of author history.",
        "interpretation":"Native rejection can change class state with program unchanged, exactly as Alice intends. No evidence of harmful exploration or an action-generated adversarial proposal.",
        "api_requests":0, "gpu_work":False, "new_environment_interactions":0,
        "autonomous_task_episodes":0, "completed_at_utc":datetime.now(timezone.utc).isoformat(),
    })


if __name__ == "__main__":
    main()
