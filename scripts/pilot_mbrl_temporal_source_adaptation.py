"""Short native gate for temporal-order imprinting in an online ensemble.

The source is generated by legal Pusher actions.  ``phase`` and
``shuffled_phase`` contain exactly the same action multiset and transition
budget, but the latter replays the source rows in a fresh simulator in a
permuted temporal order.  The learner consumes sequential minibatches so the
order variable is explicit.  This is a cross-carrier check of the only
remaining positive TD-MPC2 phenomenon, not a scale experiment.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import time
from pathlib import Path

import numpy as np
import torch

from mbrl.env.pets_pusher import PusherEnv
from mbrl.types import TransitionBatch
from pilot_mbrl_rank_general import make_model, model_hash, reset
from pilot_mbrl_ensemble_sync_adaptation import diagnostics, plan_return, save


def collect_phase(seed, n, shuffled=False, permutation_seed=77):
    env = PusherEnv(); obs, _ = reset(env, "pusher", seed)
    rows = []
    for i in range(n):
        phase = i % 16
        action = np.zeros(7, dtype=np.float32)
        action[0] = 1.5 * np.sin(phase * np.pi / 4)
        action[1] = 1.5 * np.cos(phase * np.pi / 4)
        action[2] = 1.25 * (1.0 if phase < 8 else -1.0)
        action[3:] = 0.5 * np.sin((phase + np.arange(4)) * np.pi / 2)
        nxt, reward, done, truncated, _ = env.step(action)
        rows.append((obs.copy(), action.copy(), np.asarray(nxt, dtype=np.float32).copy(),
                     float(reward), bool(done), bool(truncated)))
        obs = nxt
        if done or truncated:
            obs, _ = reset(env, seed + i + 1)
    env.close()
    if shuffled:
        rng = np.random.default_rng(permutation_seed)
        rows = [rows[i] for i in rng.permutation(len(rows))]
    data = [np.asarray(x, dtype=bool if j >= 4 else np.float32)
            for j, x in enumerate(zip(*rows))]
    return TransitionBatch(*data)


def adapt_sequential(model, source, updates, batch_size=32):
    optimizer = torch.optim.Adam(model.parameters(), lr=1e-3, weight_decay=5e-5)
    losses = []
    n = len(source)
    for update in range(updates):
        start = (update * batch_size) % n
        idx = np.arange(start, start + batch_size) % n
        loss, _ = model.update(source[idx], optimizer)
        losses.append(float(loss.detach().cpu()) if torch.is_tensor(loss) else float(loss))
    return losses


def main(args):
    out = Path(args.output); out.mkdir(parents=True, exist_ok=False)
    srcs = ["scripts/pilot_mbrl_temporal_source_adaptation.py", "scripts/pilot_mbrl_ensemble_sync_adaptation.py"]
    save(out / "plan.json", dict(arguments=vars(args), hashes={p: hashlib.sha256(Path(p).read_bytes()).hexdigest() for p in srcs},
         operation="Legal phase-locked Pusher source versus exact action-multiset shuffle; sequential online updates; native CEM victim.",
         controls="clean, random source, phase source, shuffled phase source; same source steps and update dose.",
         promotion_gate="Require phase-specific CEM loss against random and shuffled with <=5% held-out one-step mean RMSE change and a phase-specific residual/order metric.",
         api_requests=0, gpu_work=False))
    base = make_model("pusher"); base.load(Path(args.model)); base.eval(); base_digest = model_hash(base)
    validation = collect_phase(900, args.validation_steps, shuffled=False, permutation_seed=909)
    rows = []; started = time.monotonic()
    for condition in ["clean", "random", "phase", "shuffled_phase"]:
        model = make_model("pusher"); model.load(Path(args.model)); model.eval()
        losses = []
        if condition == "random":
            from pilot_mbrl_ensemble_sync_adaptation import collect
            source = collect(args.source_seed, "random", args.source_steps, args.permutation_seed)
            losses = adapt_sequential(model, source, args.updates, args.batch_size)
        elif condition in ["phase", "shuffled_phase"]:
            source = collect_phase(args.source_seed, args.source_steps,
                                   shuffled=condition == "shuffled_phase",
                                   permutation_seed=args.permutation_seed)
            losses = adapt_sequential(model, source, args.updates, args.batch_size)
        diag = diagnostics(model, validation)
        returns = [plan_return(model, seed, args) for seed in args.eval_seeds]
        row = dict(condition=condition, source_steps=0 if condition == "clean" else args.source_steps,
                   updates=args.updates, adaptation_loss_tail=losses[-5:], diagnostics=diag,
                   returns=returns, mean_return=float(np.mean([r['return_'] for r in returns])),
                   model_hash=model_hash(model))
        rows.append(row); save(out / (condition + ".json"), row); print(json.dumps(row), flush=True)
    assert model_hash(base) == base_digest
    result = dict(status="completed", base_model_hash=base_digest, rows=rows,
                  elapsed_seconds=time.monotonic()-started, api_requests=0, gpu_work=False,
                  decision="screen_only_pending_gate")
    save(out / "summary.json", result); print(json.dumps(result), flush=True)


if __name__ == "__main__":
    p = argparse.ArgumentParser(); p.add_argument("--model", required=True); p.add_argument("--output", required=True)
    p.add_argument("--source-seed", type=int, default=31); p.add_argument("--validation-steps", type=int, default=500)
    p.add_argument("--source-steps", type=int, default=120); p.add_argument("--updates", type=int, default=5)
    p.add_argument("--batch-size", type=int, default=32); p.add_argument("--permutation-seed", type=int, default=77)
    p.add_argument("--eval-seeds", nargs="+", type=int, default=[31, 32]); p.add_argument("--particles", type=int, default=10)
    p.add_argument("--horizon", type=int, default=15); p.add_argument("--max-steps", type=int, default=15)
    main(p.parse_args())
