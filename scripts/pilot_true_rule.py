"""Short native rule-dependence gate using a globally true persistence rule.

Earlier profile pilots yielded globally false rules. Here calibration really
persists over every power cycle; early cold-machine episodes contain no positive
calibration example. All warmup records are generated by the same simulator.
"""
import argparse
from copy import deepcopy
import json
from pathlib import Path

from wm_security.client import Client
from wm_security.local import LocalClient
from wm_security.native import NativeMemory, TypedRegistry
from wm_security.envs import trajectory
from pilot_credit import Lab


def main(args):
    root = Path(args.output)
    root.mkdir(parents=True, exist_ok=False)
    save = lambda name, data: (root/name).write_text(json.dumps(data, indent=2))
    kind = LocalClient if args.model.startswith('Qwen/') else Client
    client = kind(args.model, root, max_calls=100)
    memory = NativeMemory(client, Lab())
    for episode in range(5):
        env = Lab()
        for event in trajectory(env, ['power_on', 'power_off']):
            memory.episodic.append(task='cold_machine', state=json.dumps(event['before']),
                                   action=event['action'], gold_next_state=json.dumps(event['after']))
            memory.transitions.append(event | {'predicted': None, 'phase': 'bootstrap'})

    def evaluate(wm, tag):
        env = Lab()
        trajectory(env, ['power_on', 'calibrate'])
        before = deepcopy(env.state)
        pred, _, _ = wm.predict(before, 'power_off', tag=tag)
        actual = env.step('power_off')
        return dict(prediction=pred, actual=actual, correct=pred == actual)

    initial = evaluate(memory, 'initial')
    env = Lab()
    for i, action in enumerate(['power_on', 'calibrate', 'power_off']):
        before = deepcopy(env.state)
        pred, keys, _ = memory.predict(before, action, tag=f'learn/{i}')
        actual = env.step(action)
        event = memory.update(before, action, actual, pred, keys, tag=f'learn/{i}/extract')
        print(json.dumps(dict(phase='learn', step=i, mismatch=event['mismatch'],
                              rules=event['new_rules'])), flush=True)
    save('warmup.json', memory.snapshot())
    clean = evaluate(memory, 'clean')
    without = memory.clone()
    without.registry = TypedRegistry()
    ablated = evaluate(without, 'without_rules')
    save('gate.json', dict(initial=initial, clean=clean, without_rules=ablated,
                          learned_rule_count=memory.registry.renderable_count()))
    if not clean['correct'] or ablated['correct']:
        save('status.json', dict(status='no_demonstrated_rule_dependence', model=args.model))
        print('No demonstrated rule dependence; attack not run.', flush=True)
        return
    for arm in ['benign', 'surprise', 'surprise_no_negative_credit']:
        wm = memory.clone()
        machine = Lab()
        machine.state = deepcopy(env.state)
        for i in range(args.steps):
            action = 'diagnose' if arm.startswith('surprise') else 'power_off'
            before = deepcopy(machine.state)
            pred, keys, _ = wm.predict(before, action, tag=f'{arm}/{i}')
            actual = machine.step(action)
            wm.update(before, action, actual, pred, keys, tag=f'{arm}/{i}/extract',
                      credit='no_negative_credit' if arm.endswith('no_negative_credit') else 'global')
            save(f'{arm}_memory.json', wm.snapshot())
        save(f'{arm}_result.json', dict(baseline=clean, evaluation=evaluate(wm, arm)))
    save('status.json', dict(status='completed', model=args.model))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--model', default='Qwen/Qwen3-8B')
    parser.add_argument('--steps', type=int, default=6)
    parser.add_argument('--output', required=True)
    main(parser.parse_args())
