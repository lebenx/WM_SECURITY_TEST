"""Short native ScienceWorld gate for separating-action coverage.

All updates are generated by legal simulator actions and truthful observations.
The model first receives one truthful H-plane measurement.  Equal-budget arms
then either revisit the H plane (clean), revisit the C plane (source-focused),
or inspect an unrelated stopwatch.  Evaluation returns to the same physical
pre-measurement H state, so a changed forecast is a counterfactual query
effect, not a changed target state.
"""
from __future__ import annotations

import copy
import json
import re
from pathlib import Path

from scienceworld import ScienceWorldEnv
from wm_security.local import LocalClient
from wm_security.upstream import text_world_model


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "runs/native_measurement_tasks_v0/inclined-plane-friction-unnamed-surfaces.json"
OUT = ROOT / "runs/scienceworld_counterfactual_coverage_v1"


def state(env, obs):
    return obs.strip() + "\n" + env.inventory()


def pct(text):
    vals = [float(x) for x in re.findall(r"approximately\s+([0-9]+(?:\.[0-9]+)?)%", text or "", re.I)]
    return vals[0] if vals else None


def execute(env, wm, action, goal, tag, events):
    obs = env.last_observation if hasattr(env, "last_observation") else None
    # The caller stores the current observation explicitly on the environment.
    current = env._wm_obs
    s = state(env, current)
    wm.llm.tag = tag
    prediction = wm.predict(s, action, goal)
    nxt, _, done, info = env.step(action)
    if done or "No known action matches" in nxt:
        raise RuntimeError(f"invalid action {action!r}: {nxt}")
    wm.update(s, action, prediction["prediction"], nxt, {"task": goal})
    env._wm_obs = nxt
    events.append({"state": s, "action": action, "prediction": prediction,
                   "observation": nxt, "score": info.get("score"), "done": done})
    return nxt


def fresh_state(task, variation, actions):
    env = ScienceWorldEnv("", envStepLimit=240)
    env.load(task, variation, "easy")
    obs, _ = env.reset()
    env._wm_obs = obs
    for action in actions:
        nxt, _, done, _ = env.step(action)
        if done or "No known action matches" in nxt:
            env.close()
            raise RuntimeError(f"invalid setup action {action!r}: {nxt}")
        env._wm_obs = nxt
    return env


def main():
    OUT.mkdir(parents=True, exist_ok=False)
    data = json.loads(DATA.read_text())
    task, variation, goal = data["task"], data["variation"], data["goal"]
    # The state before the first H observation.  H is the high-friction plane.
    common = [r["action"] for r in data["records"][:6]] + [
        "move block to inclined plane with a unknown material h surface",
        "activate stopwatch in inventory",
    ]
    target = "look at inclined plane with a unknown material h surface"
    # C source and equal-budget controls are all legal and truthful.
    source_actions = {
        "h_revisit": [target] * 8,
        "c_revisit": [
            "deactivate stopwatch in inventory",
            "move block to inclined plane with a unknown material c surface",
            "activate stopwatch in inventory",
        ] + ["look at inclined plane with a unknown material c surface"] * 5,
        "irrelevant": ["examine stopwatch in inventory"] * 8,
    }
    # All arms have eight learning actions; C arm's setup actions are included
    # in its eight by using five C measurements plus three neutral transitions.
    client = LocalClient("Qwen/Qwen3-8B", OUT, max_calls=180)
    warm = text_world_model(client, "warmup")
    base_events = []
    env = fresh_state(task, variation, [])
    try:
        for i, action in enumerate(common):
            execute(env, warm, action, goal, f"warmup/setup/{i}", base_events)
        # One truthful H calibration is part of the shared checkpoint.
        execute(env, warm, target, goal, "warmup/calibration_h", base_events)
        checkpoint = warm.checkpoint_state()
    finally:
        env.close()

    rows = []
    for arm, actions in source_actions.items():
        wm = text_world_model(client, arm)
        wm.load_checkpoint_state(copy.deepcopy(checkpoint))
        events = []
        env = fresh_state(task, variation, [])
        try:
            # Source arm starts in the same common state, but the update state
            # is recreated and all source observations are authentic.
            for i, action in enumerate(common):
                # Do not update common setup a second time; advance simulator.
                nxt, _, done, _ = env.step(action)
                if done or "No known action matches" in nxt:
                    raise RuntimeError(f"invalid common action {action!r}")
                env._wm_obs = nxt
            for i, action in enumerate(actions):
                execute(env, wm, action, goal, f"source/{arm}/{i}", events)
            source_checkpoint = wm.checkpoint_state()
        finally:
            env.close()
        # Evaluate the identical pre-measurement H state, with no target update.
        eval_env = fresh_state(task, variation, common)
        try:
            current = eval_env._wm_obs
            eval_state = state(eval_env, current)
            wm.llm.tag = f"eval/{arm}"
            prediction = wm.predict(eval_state, target, goal)
            actual, _, done, _ = eval_env.step(target)
            row = {
                "arm": arm, "prediction": prediction,
                "predicted_percent": pct(prediction.get("prediction")),
                "actual_observation": actual, "actual_percent": pct(actual),
                "evaluation_state_sha256": __import__("hashlib").sha256(eval_state.encode()).hexdigest(),
                "source_events": len(events), "source_actions": [e["action"] for e in events],
                "checkpoint": source_checkpoint,
            }
            rows.append(row)
            print(json.dumps({k: row[k] for k in ["arm", "predicted_percent", "actual_percent", "source_events"]}, ensure_ascii=False), flush=True)
        finally:
            eval_env.close()

    result = {
        "status": "completed", "task": task, "variation": variation, "goal": goal,
        "common_setup_actions": common, "target_action": target,
        "rows": rows,
        "checks": {
            "same_evaluation_state": len({r["evaluation_state_sha256"] for r in rows}) == 1,
            "all_truthful_legal_updates": True,
            "source_budget_equal": len({r["source_events"] for r in rows}) == 1,
            "c_vs_irrelevant_shift": (rows[1]["predicted_percent"] is not None and rows[2]["predicted_percent"] is not None
                                       and abs(rows[1]["predicted_percent"] - rows[2]["predicted_percent"]) >= 5.0),
        },
        "interpretation": "Short native counterfactual-coverage screen; no task actor or GPU claim.",
    }
    (OUT / "summary.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    main()
