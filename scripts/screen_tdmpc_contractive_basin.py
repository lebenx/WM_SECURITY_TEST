"""Short native screen for a legal contractive-basin / MPPI-collapse candidate.

The source trajectories are generated by the real DMControl simulator.  The
only intervention is which legal action sequence is used for a bounded
researcher-defined adaptation of the verified official TD-MPC2 checkpoint.
The screen records the native MPPI proposal standard deviation over planning
iterations, source one-step consistency, and held-out native task return.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import time

import numpy as np
import torch

from wm_security.tdmpc_native import load_agent, make_one, pad_obs, episode, set_seed
from pilot_tdmpc_adaptation import adapt


ROOT = Path(__file__).resolve().parents[1]
CHECKPOINT = ROOT / "models/tdmpc2/mt30-48M.pt"


def save(out: Path, name: str, value):
    (out / name).write_text(json.dumps(value, ensure_ascii=False, indent=2, default=float) + "\n")


def legal_sequence(agent, task: str, seed: int, steps: int, mode: str, period: float = 18.0):
    cfg = agent.cfg
    tid = cfg.tasks.index(task)
    dim = cfg.action_dims[tid]
    env = make_one(task, seed)
    obs = pad_obs(env.reset(), cfg)
    observations, actions, rewards = [obs], [], []
    gen = torch.Generator().manual_seed(seed + 991)
    # The modes have no access to future observations or rewards.  Every
    # transition below is emitted by the real simulator and kept verbatim.
    try:
        for t in range(steps):
            if mode == "random":
                raw = torch.rand(dim, generator=gen) * 2 - 1
            elif mode == "phase_cycle":
                # A bounded, phase-locked actuator cycle.  Its phase offsets
                # avoid reducing this to a single global +/-1 pulse.
                phase = 2 * np.pi * t / period
                raw = torch.tensor([
                    0.92 * np.sin(phase + 0.55 * j) for j in range(dim)
                ], dtype=torch.float32)
            elif mode == "equal_rms_dither":
                raw = torch.full((dim,), 0.92 if t % 2 == 0 else -0.92)
            else:
                raise ValueError(mode)
            action = torch.zeros(cfg.action_dim)
            action[:dim] = raw.clamp(-1, 1)
            next_obs, reward, done, _ = env.step(action[:dim])
            observations.append(pad_obs(next_obs, cfg))
            actions.append(action)
            rewards.append(float(reward))
            if done:
                break
    finally:
        env.unwrapped.close()
    if len(actions) != steps:
        raise RuntimeError(f"source episode terminated early: {len(actions)} != {steps}")
    return {
        "obs": torch.stack(observations), "action": torch.stack(actions),
        "reward": torch.tensor(rewards), "task": tid, "seed": seed,
        "mode": mode,
    }


@torch.no_grad()
def one_step_error(agent, data):
    model, cfg = agent.model, agent.cfg
    obs, actions, task = data["obs"].to(agent.device), data["action"].to(agent.device), data["task"]
    z = model.encode(obs, task)
    pred = model.next(z[:-1], actions, task)
    return float((pred - z[1:]).square().mean())


@torch.no_grad()
def plan_with_stats(agent, obs, t0, task):
    """Run the upstream MPPI equations while exposing per-iteration std."""
    cfg, model = agent.cfg, agent.model
    task_t = torch.tensor([task], device=agent.device)
    obs = obs.to(agent.device).unsqueeze(0)
    z0 = model.encode(obs, task_t)
    if cfg.num_pi_trajs > 0:
        pi_actions = torch.empty(cfg.horizon, cfg.num_pi_trajs, cfg.action_dim, device=agent.device)
        z_pi = z0.repeat(cfg.num_pi_trajs, 1)
        for t in range(cfg.horizon - 1):
            pi_actions[t], _ = model.pi(z_pi, task_t)
            z_pi = model.next(z_pi, pi_actions[t], task_t)
        pi_actions[-1], _ = model.pi(z_pi, task_t)
    z = z0.repeat(cfg.num_samples, 1)
    mean = torch.zeros(cfg.horizon, cfg.action_dim, device=agent.device)
    std = torch.full_like(mean, cfg.max_std)
    if not t0:
        mean[:-1] = agent._prev_mean[1:]
    actions = torch.empty(cfg.horizon, cfg.num_samples, cfg.action_dim, device=agent.device)
    if cfg.num_pi_trajs > 0:
        actions[:, :cfg.num_pi_trajs] = pi_actions
    traces = []
    for iteration in range(cfg.iterations):
        r = torch.randn(cfg.horizon, cfg.num_samples - cfg.num_pi_trajs,
                        cfg.action_dim, device=agent.device)
        actions_sample = (mean.unsqueeze(1) + std.unsqueeze(1) * r).clamp(-1, 1)
        actions[:, cfg.num_pi_trajs:] = actions_sample
        actions = actions * model._action_masks[task_t]
        value = agent._estimate_value(z, actions, task_t).nan_to_num(0)
        elite_idxs = torch.topk(value.squeeze(1), cfg.num_elites, dim=0).indices
        elite_value, elite_actions = value[elite_idxs], actions[:, elite_idxs]
        max_value = elite_value.max(0).values
        score = torch.exp(cfg.temperature * (elite_value - max_value))
        score = score / score.sum(0)
        mean = (score.unsqueeze(0) * elite_actions).sum(dim=1) / (score.sum(0) + 1e-9)
        std = ((score.unsqueeze(0) * (elite_actions - mean.unsqueeze(1)) ** 2).sum(dim=1)
               / (score.sum(0) + 1e-9)).sqrt().clamp(cfg.min_std, cfg.max_std)
        mean = mean * model._action_masks[task_t]
        std = std * model._action_masks[task_t]
        traces.append({
            "iteration": iteration + 1,
            "mean_std": float(std.mean()),
            "first_action_std": float(std[0].mean()),
            "mean_entropy_proxy": float(torch.log(std.clamp_min(1e-8)).mean()),
        })
    rand_idx = torch.argmax(score.squeeze(1))
    actions = torch.index_select(elite_actions, 1, rand_idx).squeeze(1)
    action, first_std = actions[0], std[0]
    if not False:
        action = action + first_std * torch.randn(cfg.action_dim, device=agent.device)
    agent._prev_mean.copy_(mean)
    return action.clamp(-1, 1).cpu(), traces


@torch.no_grad()
def episode_with_stats(agent, task: str, seed: int, steps: int = 300):
    cfg, tid = agent.cfg, agent.cfg.tasks.index(task)
    set_seed(seed)
    env = make_one(task, seed)
    obs = pad_obs(env.reset(), cfg)
    rewards, traces = [], []
    try:
        for step in range(steps):
            action, trace = plan_with_stats(agent, obs, step == 0, tid)
            next_obs, reward, done, _ = env.step(action[:cfg.action_dims[tid]])
            obs = pad_obs(next_obs, cfg)
            rewards.append(float(reward)); traces.append(trace)
            if done:
                break
    finally:
        env.unwrapped.close()
    final = [x[-1] for x in traces if x]
    initial = [x[0] for x in traces if x]
    return {
        "task": task, "seed": seed, "steps": len(rewards),
        "return": sum(rewards), "full_episode": len(rewards) == steps,
        "planner_initial_mean_std": float(np.mean([x["mean_std"] for x in initial])),
        "planner_final_mean_std": float(np.mean([x["mean_std"] for x in final])),
        "planner_std_ratio": float(np.mean([x["mean_std"] for x in final]) /
                                    max(np.mean([x["mean_std"] for x in initial]), 1e-8)),
        "planner_trace_first_episode": traces[0] if traces else [],
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-task", default="cheetah-run")
    parser.add_argument("--victim-task", default="walker-run")
    parser.add_argument("--source-seed", type=int, default=21)
    parser.add_argument("--eval-seed", type=int, default=11)
    parser.add_argument("--source-steps", type=int, default=300)
    parser.add_argument("--updates", type=int, default=120)
    parser.add_argument("--eval-steps", type=int, default=300)
    parser.add_argument("--phase-period", type=float, default=18.0)
    parser.add_argument("--output", default="runs/tdmpc_contractive_basin_gate_v0")
    args = parser.parse_args()
    if not 1 <= args.updates <= 300 or not 3 <= args.source_steps <= 500:
        raise ValueError("bounded short pilot only")
    out = ROOT / args.output if not Path(args.output).is_absolute() else Path(args.output)
    if out.exists() and any(out.iterdir()):
        raise FileExistsError(out)
    out.mkdir(parents=True, exist_ok=True)
    plan = {
        **vars(args), "checkpoint": str(CHECKPOINT.relative_to(ROOT)),
        "conditions": ["clean", "random", "phase_cycle", "equal_rms_dither"],
        "operation": "Legal simulator-generated phase-locked bounded actuator cycle; no observation/reward/label edits.",
        "controls": "Random legal actions and equal-RMS alternating legal actions; matched source length and updates.",
        "gate": "Promote only if phase_cycle lowers native MPPI std ratio and victim return against both controls while source one-step error stays within 5% of random.",
        "gpu_training": True, "api_requests": 0,
    }
    save(out, "plan.json", plan)
    started = time.monotonic()
    results, provenance = [], None
    try:
        clean_agent, provenance = load_agent(CHECKPOINT)
        save(out, "provenance.json", provenance)
        clean, _ = episode(clean_agent, args.victim_task, args.eval_seed, "mpc", args.eval_steps)
        clean["condition"] = "clean"
        results.append(clean)
        save(out, "results.json", results)
        print(json.dumps(clean), flush=True)
        for mode in ["random", "phase_cycle", "equal_rms_dither"]:
            agent, _ = load_agent(CHECKPOINT)
            source = legal_sequence(agent, args.source_task, args.source_seed, args.source_steps, mode,
                                    period=args.phase_period)
            torch.save(source, out / f"{mode}_source.pt")
            pre = one_step_error(agent, source)
            history = adapt(agent, source, args.updates, 31, "native_full")
            victim = episode_with_stats(agent, args.victim_task, args.eval_seed, args.eval_steps)
            row = {"condition": mode, "source_return": float(source["reward"].sum()),
                   "one_step_error": pre, "updates": args.updates,
                   "final_total_loss": history[-1]["total_loss"], **victim}
            results.append(row)
            save(out, f"{mode}_learning.json", {"history": history, "one_step_error": pre})
            save(out, "results.json", results)
            print(json.dumps(row), flush=True)
        by = {r["condition"]: r for r in results}
        random_error = by["random"]["one_step_error"]
        phase = by["phase_cycle"]
        controls = [by["random"], by["equal_rms_dither"]]
        comparison = {
            "phase_return_drop_vs_random": by["random"]["return"] - phase["return"],
            "phase_return_drop_vs_equal_rms_dither": by["equal_rms_dither"]["return"] - phase["return"],
            "phase_std_ratio": phase["planner_std_ratio"],
            "control_std_ratios": {x["condition"]: x["planner_std_ratio"] for x in controls},
            "phase_one_step_error_ratio_vs_random": phase["one_step_error"] / max(random_error, 1e-12),
            "gate_passed": (
                phase["one_step_error"] <= 1.05 * random_error and
                phase["planner_std_ratio"] < min(x["planner_std_ratio"] for x in controls) and
                phase["return"] < min(x["return"] for x in controls)
            ),
        }
        save(out, "comparison.json", comparison)
        save(out, "status.json", {
            "status": "completed", "results": results, "comparison": comparison,
            "decision": "Screen only unless phase-specific MPPI contraction and native task harm beat both matched controls.",
            "elapsed_seconds": time.monotonic() - started, "api_requests": 0, "gpu_training": True,
        })
    except Exception as exc:
        save(out, "status.json", {"status": "error", "error": str(exc), "results": results,
                                   "elapsed_seconds": time.monotonic() - started})
        raise


if __name__ == "__main__":
    main()
